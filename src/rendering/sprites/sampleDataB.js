// Tile Rumput Arah B (40x40 px)
const grassTileB = Array.from({ length: 40 }, (_, y) => {
  let row = "9".repeat(40);
  if (y % 7 === 1) row = row.slice(0, 10) + "A" + row.slice(11, 28) + "88" + row.slice(30);
  if (y % 9 === 4) row = row.slice(0, 22) + "AA" + row.slice(24, 35) + "8" + row.slice(36);
  if (y % 11 === 6) row = row.slice(0, 4) + "88" + row.slice(6, 17) + "A" + row.slice(18);
  if (y === 15) row = row.slice(0, 14) + "34" + row.slice(16); // kerikil batu kecil
  if (y === 16) row = row.slice(0, 14) + "23" + row.slice(16);
  return row;
});

// Pohon Arah B (48x64 px)
const treeObjectB = Array.from({ length: 64 }, (_, y) => {
  if (y < 42) {
    // Kanopi rimbun cemara/pinus senja (E = shadow, F = mid, G = light)
    const span = Math.min(22, Math.floor(y * 0.55) + 3);
    const left = 24 - span;
    const right = 24 + span;
    let line = ".".repeat(left);
    for (let x = left; x <= right; x++) {
      if (x === left || x === right) line += "0";
      else if (x < 22 && y < 35) line += (x < 18 ? "G" : "F");
      else line += (x > 26 ? "E" : "F");
    }
    line += ".".repeat(48 - line.length);
    return line;
  } else if (y < 56) {
    // Batang pohon pinus bercabang (B, C, D)
    return ".".repeat(20) + "0BCCDD0" + ".".repeat(21);
  } else {
    // Bayangan tanah di-bake (1 = night-abyss)
    const shadowSpan = Math.max(0, 18 - Math.abs(y - 59) * 4);
    if (shadowSpan <= 0) return ".".repeat(48);
    const sLeft = 24 - shadowSpan;
    return ".".repeat(sLeft) + "0" + "1".repeat(shadowSpan * 2 - 1) + "0" + ".".repeat(48 - (sLeft + shadowSpan * 2 + 1));
  }
});

